def review_file_request(request_id, admin_user_id, approve=True, note=""):
    conn = get_connection()
    try:
        actor = _get_user(conn, admin_user_id)
        if not _is_admin(actor):
            raise PermissionError("Only an Admin can review requests.")
        req = conn.execute(
            """SELECT r.*, f.status AS file_status, f.deleted_at AS file_deleted_at,
                          f.file_id AS file_id, f.file_name AS file_name
                   FROM file_requests r JOIN files f ON f.id=r.file_row_id
               WHERE r.id=? AND r.status='PENDING'""", (int(request_id),)
        ).fetchone()
        if not req:
            raise ValueError("Pending request not found.")
        req = dict(req)
        now = _utc_now()
        status = "APPROVED" if approve else "REJECTED"
        if approve and req["request_type"] == "DELETE":
            if req.get("file_deleted_at"):
                raise ValueError("This file has already been deleted.")
            if req.get("file_status") == "OUT":
                raise ValueError("Return the file before approving deletion.")
            conn.execute(
                "UPDATE files SET deleted_at=?, deleted_by=?, updated_at=?, updated_by=? WHERE id=? AND deleted_at IS NULL",
                (now, actor["id"], now, actor["id"], req["file_row_id"]),
            )
        elif approve and req["request_type"] == "MODIFY":
            payload = json.loads(req.get("payload") or "{}")
            allowed = {"file_name", "department", "section"}
            if not payload or set(payload) - allowed:
                raise ValueError("Invalid modification request payload.")
            conn.execute(
                """UPDATE files SET file_name=?, department=?, section=?, updated_at=?,
                   updated_by=?, approval_status='PENDING' WHERE id=? AND deleted_at IS NULL""",
                (payload["file_name"], payload["department"], payload.get("section"),
                 now, actor["id"], req["file_row_id"]),
            )
        elif approve and req["request_type"] == "RETRIEVE":
            file_row = conn.execute("SELECT * FROM files WHERE id=?", (req["file_row_id"],)).fetchone()
            if not file_row or file_row["deleted_at"]:
                raise ValueError("File is not active.")
            if file_row["status"] != "AVAILABLE":
                raise ValueError("File is not available.")
            conn.execute("UPDATE files SET status='OUT', current_holder_id=? WHERE id=?",
                         (req["requester_id"], req["file_row_id"]))
            conn.execute(
                """INSERT INTO file_movements (file_id,user_id,action,movement_time,remarks)
                   VALUES (?,?,'ISSUED',?,?)""",
                (req["file_row_id"], req["requester_id"], now, "Approved retrieval request"),
            )
        conn.execute(
            """UPDATE file_requests SET status=?, reviewed_by=?, reviewed_at=?, review_note=?
               WHERE id=?""", (status, actor["id"], now, (note or "").strip() or None, request_id)
        )
        requester = conn.execute("SELECT name FROM users WHERE id=?", (req["requester_id"],)).fetchone()
        _notify_user(conn, req["requester_id"], f"Request {status.lower()}",
                     f"Your {req['request_type'].lower()} request for {req['file_id']} was {status.lower()}. {note or ''}",
                     "REQUEST_UPDATE")
        audit_file = conn.execute("SELECT * FROM files WHERE id=?", (req["file_row_id"],)).fetchone()
        _audit(conn, audit_file, actor, "FILE_REQUEST_REVIEWED", "PENDING", status,
               details=f"Request #{request_id}: {req['request_type']}; {note or ''}")
        conn.commit()
        return status
    finally:
        conn.close()


