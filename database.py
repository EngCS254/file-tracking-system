def admin_delete_user(admin_user_id, target_user_id):
    conn = get_connection()
    try:
        actor = _get_user(conn, admin_user_id)
        if not _is_admin(actor):
            raise PermissionError("Only an Admin can deactivate user accounts.")
        target = conn.execute("SELECT * FROM users WHERE id=?", (int(target_user_id),)).fetchone()
        if not target:
            raise ValueError("User not found.")
        if int(target["id"]) == actor["id"]:
            raise ValueError("You cannot deactivate your own account.")
        if str(target["role"]).strip().lower() == "admin":
            admins = conn.execute("SELECT COUNT(*) FROM users WHERE active=1 AND LOWER(role)='admin'").fetchone()[0]
            if admins <= 1:
                raise ValueError("The last active administrator cannot be deactivated.")
        conn.execute("UPDATE users SET active=0 WHERE id=?", (int(target_user_id),))
        _audit(conn, None, actor, "USER_DEACTIVATED", "ACTIVE", "INACTIVE",
               details=f"Account {target['staff_number']} deactivated")
        conn.commit()
        return True
    finally:
        conn.close()


